/** Отказ по лимиту сообщений сессии. web — байт в байт прежний текст маршрута чата; telegram — новый разговор командой /new */
export function limitText(ch: Channel, limit: number): string {
  return ch === "telegram"
    ? `В этом разговоре лимит ${limit} сообщений исчерпан. Отправьте /new, чтобы начать новую проверку.`
    : `В этой сессии лимит ${limit} сообщений исчерпан. Обновите страницу, чтобы начать новую проверку.`;
}

