/** Явный вопрос (шаг 1 findTerm, см. шапку). «что за» / «что это за» базовую статью не открывают («что за облигация Магнит?») */
const ASK = [
  "что такое", "что значит", "что значат", "что означает", "что означают", "что обозначает", "что за", "что это за",
  "объясни", "объясните", "поясни", "поясните", "расскажи", "расскажите", "what is", "what are", "what does",
].map((s) => s.split(" "));
/** Вопрос после слова — только в конце предложения («а купон это что?»); в середине это союз («говорил, что это надёжнее») */
const POST = [["это", "что"], ["что", "это"]];
/** Слова прямо перед термином из aliases, которые не меняют понятия: степень («большая дюрация») или голова («уровень листинга»,
 *  «дата оферты», «ставка налога», «низкий уровень листинга»). Другое слово перед термином — другое понятие: «кредитный скоринг»,
 *  «налоговый вычет» */
const LEAD = /^(больш|небольш|маленьк|длинн|коротк|высок|низк|широк|узк|уровен|уровн|дат[аеуы]?$|срок|ставк|размер|график|услови)/;
/** Бытовые слова на расстоянии одной буквы от основы: опечаткой не считаются («лифтинг» — не «листинг») */
const NOT_TYPO = /^лифтинг/;
/** Базовые слова-рамки: уступают термину из aliases в том же вопросе («облигация с офертой», «флаг «Длинная дюрация»») и любому
 *  термину, если стоят не первыми («номинал облигации»); «что такое облигация и купон» — два вопроса, null */
const FRAMING = new Set(["bond", "ofz", "truth"]);

/**
 * Признаки вопроса-сравнения. Статья «Облигация и вклад» находится по двум базовым словам рядом, а вклад и облигация
 * часто стоят в реплике как контекст: «Мне вместо вклада предлагают облигацию с офертой — что такое оферта?», «Банк вместо
 * вклада предлагает облигации. Что такое купон?». Поэтому она открывается только в сравнении, плотной парой или одна (см. шапку)
 */
const COMPARE = /^(отлича|отличи[ея]|разниц|различ|лучше|хуже|выгодн|надежн|безопасн|сравн|рискованн|доходнее|или$|vs$|versus$|против$)/;
/** Базовые слова самой пары «облигация … вклад»: рядом с ними пара остаётся единственным вопросом реплики */
const PAIR_IDS = new Set(["bond", "ofz", "deposit"]);

/** Конец предложения: ? ! … ; перевод строки, точка (кроме точки между цифрами: «18.5%») */
const SENTENCE_BREAK = /[?!…;\n]|(?<!\d)\.|\.(?!\d)/;
/** Границы фраз внутри предложения: запятая (кроме «18,5%»), двоеточие, тире */
const CLAUSE_BREAK = /[:—–]|\s-\s|(?<!\d),|,(?!\d)/;

const norm = (s: string) => s.toLowerCase().replace(/ё/g, "е");

/** Слова реплики, номер фразы и предложения каждого слова, кончается ли предложение знаком «?»; «Г-спред» кириллицей — тот же
 *  G-спред (а «в 2025 г. спред» — нет) */
function tokenize(text: string): { ws: string[]; clause: number[]; sent: number[]; asks: boolean[] } {
  const ws: string[] = [];
  const clause: number[] = [];
  const sent: number[] = [];
  let c = 0;
  const t = norm(text).replace(/(?<![a-zа-я0-9])г-(?=спред)/g, "g-");
  t.split(SENTENCE_BREAK).forEach((s, si) =>
    s.split(CLAUSE_BREAK).forEach((part) => {
      for (const w of part.match(/[a-zа-я0-9]+%?/g) ?? []) { ws.push(w); clause.push(c); sent.push(si); }
      c++;
    }));
  return { ws, clause, sent, asks: (t.match(new RegExp(SENTENCE_BREAK, "g")) ?? []).map((m) => m === "?") };
}

function parseAlias(a: string): Pattern {
  return norm(a).split(/\s*…\s*/).map((part) =>
    part.split(/\s+/).filter(Boolean).map((w): AliasWord =>
      w.endsWith("$") ? { s: w.slice(0, -1), mode: "word" } : w.endsWith("+") ? { s: w.slice(0, -1), mode: "forms" } : { s: w, mode: "stem" }));
}

/** Расстояние Дамерау–Левенштейна (вариант с соседними перестановками) */
function editDistance(a: string, b: string): number {
  const d: number[][] = Array.from({ length: a.length + 1 }, (_, i) => Array.from({ length: b.length + 1 }, (_, j) => (i === 0 ? j : j === 0 ? i : 0)));
  for (let i = 1; i <= a.length; i++)
    for (let j = 1; j <= b.length; j++) {
      d[i][j] = Math.min(d[i - 1][j] + 1, d[i][j - 1] + 1, d[i - 1][j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
      if (i > 1 && j > 1 && a[i - 1] === b[j - 2] && a[i - 2] === b[j - 1]) d[i][j] = Math.min(d[i][j], d[i - 2][j - 2] + 1);
    }
  return d[a.length][b.length];
}

function wordMatches(w: string, a: AliasWord): boolean {
  const L = a.s.length;
  // точное совпадение: основа — начало слова; «основа+» — дальше только окончание; «слово$» — слово целиком
  if (w.startsWith(a.s) && (a.mode === "stem" || (a.mode === "word" ? w.length === L : ENDINGS.has(w.slice(L))))) return true;
  // опечатка: начало слова отличается от основы на одну букву, а за ним — только окончание (у «слова$» — ничего):
  // «драции» = «драци»+«и» ~ «дюраци»; «дурацкий» — нет («дурац»+«кий» — не окончание)
  if (L < FUZZY_STEM_MIN || w.length < FUZZY_WORD_MIN || NOT_TYPO.test(w)) return false;
  const last = a.s[L - 1];
  for (const k of [L - 1, L, L + 1]) {
    if (k > w.length || (a.mode === "word" ? k !== w.length : !ENDINGS.has(w.slice(k)))) continue;
    const p = w.slice(0, k);
    if (p[0] === a.s[0] && (p[k - 1] === last || (last === "и" && p[k - 1] === "ы")) && editDistance(p, a.s) <= 1) return true;
  }
  return false;
}

/** Совпадение алиаса, начиная со слова i: индекс за последним совпавшим словом или null */
function matchAt(ws: string[], i: number, pat: Pattern): number | null {
  let pos = i;
  for (let pi = 0; pi < pat.length; pi++) {
    const part = pat[pi];
    const fits = (at: number) => at + part.length <= ws.length && part.every((aw, k) => wordMatches(ws[at + k], aw));
    if (pi === 0) {
      if (!fits(pos)) return null;
      pos += part.length;
      continue;
    }
    let at = pos;
    while (at <= pos + GAP && at + part.length <= ws.length && !fits(at)) at++;
    if (at > pos + GAP || at + part.length > ws.length) return null;
    pos = at + part.length;
  }
  return pos;
}

const compile = (t: Term, list: string[]) => ({ t, patterns: list.map(parseAlias) });
const EXACT = GLOSSARY.map((t) => compile(t, t.aliases));
const BASIC = GLOSSARY.filter((t) => t.basic?.length).map((t) => compile(t, t.basic ?? []));
/** Заголовки статей словами реплики: «Налог на доход по облигациям» */
const TITLES = new Map(GLOSSARY.map((t) => [tokenize(t.title).ws.join(" "), t]));

/** Все вхождения алиасов словаря в реплике */
function hits(ws: string[], dict: typeof EXACT, basic: boolean): Hit[] {
  const out: Hit[] = [];
  for (const { t, patterns } of dict)
    for (const pat of patterns)
      for (let i = 0; i < ws.length; i++) {
        const end = matchAt(ws, i, pat);
        if (end != null) out.push({ t, start: i, end, basic });
      }
  return out;
}

/** Без совпадений внутри более длинного: «облигация ОФЗ» — ОФЗ, «плавающим купоном» — флоатер, «G-спред» — не «спред» */
const top = (hs: Hit[]) => hs.filter((h) => !hs.some((x) => x.start <= h.start && x.end >= h.end && x.end - x.start > h.end - h.start));

export function findTerm(q: string): Term | null {
  if (q.length > MAX_CHARS) return null;
  // номер выпуска ОФЗ в реплике (в том числе слитно: «ОФЗ26238», «OFZ26238») — речь о бумаге, а не о термине: решает модель
  if (/(?:офз|ofz)[\s-]*\d/i.test(q)) return null;
  const { ws, clause, sent, asks } = tokenize(q);
  const phraseAt = (list: string[][], i: number) => list.find((p) => p.every((w, k) => ws[i + k] === w));
  const compare = ws.some((w) => COMPARE.test(w));
  const all = hits(ws, EXACT, false);
  const terms = all.filter((h) => h.t.id !== "deposit");
  const pairs = all.filter((h) => h.t.id === "deposit");
  const basic = hits(ws, BASIC, true);
  // пара «облигация … вклад» — в сравнении или плотная: «облигация и вклад», «вклад облигация»
  const okPairs = pairs.filter((h) => compare || ws.slice(h.start + 1, h.end - 1).every((w) => w === "и"));
  // слова терминов и базовых слов (крайние слова пары — базовые, слова между ними — нет) и слово LEAD перед термином
  const known = ws.map(() => false);
  for (const h of [...terms, ...basic]) for (let k = h.start; k < h.end; k++) known[k] = true;
  for (const h of terms) for (let k = h.start - 1; k >= 0 && LEAD.test(ws[k]); k--) known[k] = true; // «низкий уровень листинга»
  // слово сравнения рядом с парой «облигация … вклад» — часть вопроса о ней («что лучше: ОФЗ или вклад?»)
  const plain = (from: number, to: number) =>
    ws.slice(from, to).every((w, k) => known[from + k] || FRAME.has(w) || (pairs.length > 0 && COMPARE.test(w)));
  // термин один, иначе null (from — первое содержательное слово вопроса); слово-рамка уступает (FRAMING); после «что за»
  // базовая статья не открывается
  const single = (hs: Hit[], from: number, za = false): Term | null => {
    const tops = top(hs);
    const alias = tops.some((h) => !h.basic);
    if (za && !alias) return null;
    const ts = new Set(tops.filter((h) => !(h.basic && FRAMING.has(h.t.id) && (alias || h.start > from))).map((h) => h.t));
    const t = ts.size === 1 ? [...ts][0] : null;
    // слово «спред» при ОФЗ где угодно в реплике — скорее G-спред («спред между облигацией и ОФЗ»), но не наверняка: не «Спред в
    // стакане», а модель (G-спред — только алиасом: «спред к ОФЗ»)
    return t?.id === "spread" && ws.some((w) => w.startsWith("спред")) && basic.some((h) => h.t.id === "ofz") ? null : t;
  };
  // первое содержательное слово единицы (фразы или предложения), где стоит слово i, но не дальше i
  const lead = (unit: number[], i: number) => {
    let s = unit.indexOf(unit[i]);
    while (s < i && FRAME.has(ws[s])) s++;
    return s;
  };

  // 1. явный вопрос: решает первый (см. шапку); вопрос — от спрошенного слова до конца реплики
  for (let i = 0; i < ws.length; i++) {
    const post = phraseAt(POST, i);
    const p = phraseAt(ASK, i) ?? (post && sent[i + post.length] !== sent[i] ? post : undefined);
    if (!p) continue;
    let from = i + p.length;
    while (from < ws.length && sent[from] === sent[i] && FRAME.has(ws[from])) from++;
    const after = from < ws.length && sent[from] === sent[i];
    // перед вопросом в его фразе («а купон что значит?»), а если фраза пуста и после вопроса слов нет — в его предложении
    // («у ОФЗ большая дюрация, что это?»)
    let s = lead(clause, i);
    if (s === i && !after) s = lead(sent, i);
    if (s === i && !after) continue; // «Дюрация. Что это?» — шаг 2
    // спрошенное слово — перед вопросом, если там термин или после вопроса слов нет («Дюрация что значит у облигации?»), иначе после
    // него, а слова перед — рассказ («Хочу понять что такое дюрация»)
    const start = s < i && (!after || known.slice(s, i).some(Boolean)) ? s : from;
    // до вопроса был другой вопрос («Ты уверен? Что такое НКД?», «Стоит ли брать? Что такое оферта?») — отвечает модель
    if (asks.slice(0, sent[i]).includes(true) || !plain(start, ws.length)) return null;
    // «Объясни, это облигация?» — вопрос, тот ли это термин (обычно о строке отчёта), а не просьба об определении: «это» среди
    // служебных слов после «объясни/поясни/расскажи», не в «что это (за)» («что такое это НКД» — об определении)
    if (start === from && !p.includes("что") && ws.slice(i + p.length, from).some((w, k) => w === "это" && ws[i + p.length + k - 1] !== "что")) return null;
    // «что за» — и после пропущенных служебных слов: «Объясни, что за ОФЗ», «Расскажи, что это за купон»
    return single([...terms, ...okPairs, ...basic].filter((h) => h.start >= start), start, ws.slice(i, from).includes("за"));
  }

  // 2. без явного вопроса («НКД», «Срок драции», «Чем облигация отличается от депозита?») — только если вся реплика и есть термин
  //    («дюрация 3 года это хорошо?», «у бумаги есть оферта» — нет). Заголовок статьи — тоже термин (так его может передать модель
  //    в explain_term). Пара — в сравнении, плотная или одна (других терминов нет, базовые слова — только облигация, ОФЗ, вклад)
  const title = TITLES.get(ws.join(" "));
  if (title) return title;
  if (!plain(0, ws.length)) return null;
  const sole = !terms.length && basic.every((x) => PAIR_IDS.has(x.t.id));
  const named = [...terms, ...(sole ? pairs : okPairs)];
  if (named.length) return single([...named, ...basic], 0);
  // одни базовые слова — с рамкой определения (DEFINE, «что это за облигация» — не рамка) или без других слов («дата погашения»)
  const bare = ws.every((w, k) => known[k] || w === "и" || w === "или");
  const define = ws.some((_, i) => { const p = phraseAt(DEFINE, i); return p != null && ws[i + p.length] !== "за"; });
  return bare || define ? single(basic, known.indexOf(true)) : null;
}
